    static func tuned(
        background: String,
        panel: String,
        raised: String,
        accent: String,
        accentDim: String,
        accentDeep: String,
        textPrimary: String,
        textSecondary: String,
        textMuted: String,
        hairline: String,
        cyan: String = "#97CFE0",
        violet: String = "#BD93F9",
        amber: String = "#FFB000",
        error: String = "#FFB4AB",
        isLight: Bool = false
    ) -> ThemePalette {
        let accentColor = Color(termHex: accent)
        let onAccentColor = TermColorMath.luminance(accentColor) > 0.45 ? Color(termHex: "#030503") : Color.white

        return ThemePalette(
            background: Color(termHex: background),
            panel: Color(termHex: panel),
            panelRaised: Color(termHex: raised),
            accent: accentColor,
            accentDim: Color(termHex: accentDim),
            accentDeep: Color(termHex: accentDeep),
            onAccent: onAccentColor,
            textPrimary: Color(termHex: textPrimary),
            textSecondary: Color(termHex: textSecondary),
            textMuted: Color(termHex: textMuted),
            hairline: Color(termHex: hairline),
            cyan: Color(termHex: cyan),
            violet: Color(termHex: violet),
            amber: Color(termHex: amber),
            error: Color(termHex: error),
            isLight: isLight
        )
    }
